class RepairWorkflowTransitionError extends Error {
  constructor(code, message, details = {}) {
    super(message);
    this.name = 'RepairWorkflowTransitionError';
    this.code = code;
    this.details = details;
  }
}

function requireKnownStatus(status) {
  if (!Object.prototype.hasOwnProperty.call(REPAIR_WORKFLOW_TRANSITIONS, status)) {
    throw new RepairWorkflowTransitionError(
      'INVALID_REPAIR_WORKFLOW_STATUS',
      `Unknown repair workflow status: ${status}`,
      { status }
    );
  }
  return status;
}

function requireKnownAction(action) {
  if (!Object.values(REPAIR_WORKFLOW_ACTION).includes(action)) {
    throw new RepairWorkflowTransitionError(
      'INVALID_REPAIR_WORKFLOW_ACTION',
      `Unknown repair workflow action: ${action}`,
      { action }
    );
  }
  return action;
}

function getAvailableRepairWorkflowActions(status) {
  requireKnownStatus(status);
  return Object.entries(REPAIR_WORKFLOW_TRANSITIONS[status]).map(([action, targetStatus]) => ({
    action,
    targetStatus,
    passportEventType: PASSPORT_EVENT_BY_ACTION[action] || 'REPAIR_STATUS_CHANGED',
  }));
}

function resolveRepairWorkflowTransition(status, action) {
  requireKnownStatus(status);
  requireKnownAction(action);

  const targetStatus = REPAIR_WORKFLOW_TRANSITIONS[status][action];
  if (!targetStatus) {
    throw new RepairWorkflowTransitionError(
      'REPAIR_WORKFLOW_TRANSITION_NOT_ALLOWED',
      `Repair workflow action ${action} is not allowed from ${status}`,
      {
        status,
        action,
        availableActions: getAvailableRepairWorkflowActions(status),
      }
    );
  }

  return {
    previousStatus: status,
    action,
    targetStatus,
    passportEventType: PASSPORT_EVENT_BY_ACTION[action] || 'REPAIR_STATUS_CHANGED',
    terminal: TERMINAL_REPAIR_WORKFLOW_STATUSES.includes(targetStatus),
  };
}

function projectLegacyServiceStatus(workflowStatus) {
  requireKnownStatus(workflowStatus);

  if (workflowStatus === REPAIR_WORKFLOW_STATUS.RECEIVED ||
      workflowStatus === REPAIR_WORKFLOW_STATUS.WAITING_DIAGNOSIS) {
    return 'RECEIVED';
  }
  if (workflowStatus === REPAIR_WORKFLOW_STATUS.WAITING_PARTS) {
    return 'WAITING_PARTS';
  }
  if (workflowStatus === REPAIR_WORKFLOW_STATUS.DELIVERED ||
      workflowStatus === REPAIR_WORKFLOW_STATUS.CLOSED) {
    return 'COMPLETED';
  }
  if (workflowStatus === REPAIR_WORKFLOW_STATUS.REJECTED ||
      workflowStatus === REPAIR_WORKFLOW_STATUS.CANCELLED) {
    return 'CANCELLED';
  }
  return 'IN_PROGRESS';
}

